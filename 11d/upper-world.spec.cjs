/* Browser acceptance: run with npx playwright test if installed. */
const { test, expect } = require('@playwright/test');
const path = require('path');
const {pathToFileURL} = require('url');
test('11D upper-world governed effect and source-preserving routes', async ({page}) => {
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(pathToFileURL(path.join(__dirname,'index.html')).href);
 await expect(page.locator('#a11')).toBeVisible();
 let health=await page.evaluate(()=>window.Aura11D.health());
 expect(health.status).toBe('LOCAL_PUBLIC_READY');
 expect(health.amelia).toBe('NOT_CONNECTED');
 await page.locator('[data-a11-tab="K27"]').click();
 await page.locator('#a11-route').click();
 let k=await page.locator('#a11-route-out').textContent();
 expect(k).toContain('"hydrated": 3');
 expect(k).toContain('LOCAL_HASH_CANDIDATE_NOT_SEMANTIC_RETRIEVAL');
 await page.locator('#a11-reopen').click();
 await expect(page.locator('#a11-route-out')).toContainText('REOPEN_LOCAL');
 await page.locator('[data-a11-tab="Workcells"]').click();
 await page.locator('#a11-author').click();
 await page.locator('#a11-deny').click();
 await page.locator('#a11-verify').click();
 await page.locator('#a11-rebase').click();
 expect((await page.evaluate(()=>window.Aura11D.state())).revision).toBe(0);
 await page.locator('#a11-author').click();
 await page.locator('#a11-approve').click();
 await page.locator('#a11-verify').click();
 await page.locator('#a11-rebase').click();
 let s=await page.evaluate(()=>window.Aura11D.state());
 expect(s.revision).toBe(1);expect(s.objects.length).toBe(1);
 await page.locator('#a11-revert').click();
 s=await page.evaluate(()=>window.Aura11D.state());
 expect(s.revision).toBe(2);expect(s.objects.length).toBe(0);
 await page.locator('[data-a11-tab="Navi"]').click();
 await page.locator('#a11-search').fill('Orphanim');
 await page.locator('#a11-search-btn').click();
 await expect(page.locator('#a11-results')).toContainText('Orphanim');
 await page.locator('[data-a11-tab="Orphanim"]').click();
 await page.locator('#a11-next').click();
 await expect(page.locator('#a11-gate-state')).toContainText('Gate 2/24');
 expect(errors).toEqual([]);
});